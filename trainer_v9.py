# шайбы-столбики Ø9 под уши (по 2 шт), винт M3 длиннее сквозь ухо и столбик
# в то же отверстие плиты. Все 4 барабана теперь ОДИНАКОВЫЕ (m1-высоты).
# Подъёмы = ZFD[k]-ZFD[0]: m2 1.25, m3 4.75, m4 8.25. Дека не меняется.
motor_risers = []
for zfd in ZFD[1:]:
    h = zfd - ZFD[0]
    r = Pos(0, 0, h / 2) * Cylinder(4.5, h)
    r -= Pos(0, 0, h / 2) * Cylinder(1.7, h + 0.2)                 # Ø3.4 под M3
    motor_risers.append(r)

# ---------------- ролики ----------------
# угловой: высокая шейка-капстан (трос заходит по дну, сходит на высоте пятки)
corner = Pos(0, 0, 0.15) * Cylinder(3.0, 0.3)
corner += Pos(0, 0, 1.4) * Cylinder(2.3, 2.2)
corner += Pos(0, 0, 2.7) * Cylinder(3.0, 0.4)
corner -= Pos(0, 0, 1.45) * Cylinder(PIN_F, 3.1)

guides = []
for zfd in ZFD:                                 # направляющий на оси M3
    g = Pos(0, 0, (0.2 + zfd - 1.2) / 2) * Cylinder(4.5, zfd - 1.4)
    g += Pos(0, 0, zfd) * Cylinder(3.5, 2.4)                       # шейка Ø7 (стенка 0.9 вокруг трубки)
    g += Pos(0, 0, zfd + 1.6) * Cylinder(4.5, 0.8)
    g -= Pos(0, 0, (zfd + 2.2) / 2) * Cylinder(2.6, zfd + 2.4)   # Ø5.2: латунная трубка K&S 5x0.9 на M3
    guides.append(g)

# ---------------- втулки направляющих (ВРЕМЕННЫЕ, вместо латунной трубки) ----
# Печатная замена K&S 5x0.45: Ø5 x Ø4.1, стенка 0.45 (один периметр сопла).
# Длина = высота ролика + 0.8 (винт зажимает втулку, ролик крутится свободно).
bushes = []
for zfd in ZFD:
    b = Pos(0, 0, (zfd + 2.6) / 2) * Cylinder(2.5, zfd + 2.6)
    b -= Pos(0, 0, (zfd + 2.6) / 2) * Cylinder(2.05, zfd + 2.8)
    bushes.append(b)

# ---------------- дека ----------------
# v9.2: рельсы грифа и упор торца — ОТДЕЛЬНЫЕ детали на винтах M3 снизу
# (иначе деку не положить плашмя на стол). В деке — карманы 0.5 мм под их
# пятки + сквозные отверстия Ø3.4; в деталях — глухие пилоты Ø2.4 (самонарез).
RAIL_HOLES = [(107, 27.2), (119, 27.2)]         # на сторону (зеркально для -Y)
STOP_HOLES = [(127.4, -5), (127.4, 5)]
deck = BB(100, 330, -30, 30, -3, 0)
for x0, x1 in ((100, 112), (209, 221), (318, 330)):
    for sg in (-1, 1):
        deck += BB(x0, x1, sg * 18, sg * 30, -29, -3)
for sg in (-1, 1):
    deck -= BB(99.8, 126.2, sg * 25.0, sg * 29.4, -0.5, 0.1)       # карман рельсы
    for hx, hy in RAIL_HOLES:
        deck -= Pos(hx, sg * hy, -1.5) * Cylinder(1.7, 3.2)        # Ø3.4 сквозное
deck -= BB(125.2, 129.6, -8.2, 8.2, -0.5, 0.1)                     # карман упора
for hx, hy in STOP_HOLES:
    deck -= Pos(hx, hy, -1.5) * Cylinder(1.7, 3.2)

# рельса грифа (2 шт, деталь симметричная — одна и та же на оба борта)
rail = BB(100, 126, 25.2, 29.2, -0.5, 8)
for hx, hy in RAIL_HOLES:
    rail -= Pos(hx, hy, 2.75) * Cylinder(1.2, 6.7)                 # пилот Ø2.4, глухой
# упор торца грифа (1 шт, по центру)
stop = BB(125.4, 129.4, -8, 8, -0.5, 8)
for hx, hy in STOP_HOLES:
    stop -= Pos(hx, hy, 2.75) * Cylinder(1.2, 6.7)
for k, m in enumerate(MOT):
    deck -= Pos(m, 0, -1.5) * Cylinder(MOT_HOLE_R, 3.2)
    deck -= BB(m - 23, m - 16, -6, 6, -3.1, 0.1)                   # вырез разъёма
    for sg in (-1, 1):
        deck -= Pos(m, sg * EAR_CC / 2, -1.5) * Cylinder(1.25, 3.2)
        deck -= Pos(GUIDE[k][0], sg * GUIDE[k][1], -1.5) * Cylinder(1.65, 3.2)  # M4 самонарез (трубка 5x0.45)
for sx, sy in DECK_SCREWS:
    deck -= Pos(sx, sy, -1.5) * Cylinder(1.25, 3.2)

# ---------------- мок мотора ----------------
mot = Pos(0, 0, -11) * Cylinder(18.25, 22)
mot += BB(-4.5, 4.5, -25.9, 25.9, 0, 1.5)
for sg in (-1, 1):
    mot += Pos(0, sg * EAR_CC / 2, 0.75) * Cylinder(3.5, 1.5)
    mot -= Pos(0, sg * EAR_CC / 2, 0.75) * Cylinder(1.6, 1.7)
mot += Pos(0, 0, 0.75) * Cylinder(8, 1.5)
mot += Pos(0, 0, 3) * Cylinder(1.25, 6)
mot += BB(-24, -16, -5.25, 5.25, -22, -14)
# заводская шестерня 10T m0.5 (Ø5.9x4), низ на z3 (замер юзера)
import math as _m
mot += Pos(0, 0, 5) * Cylinder(1.875, 4)                # тело до впадин
for k in range(10):
    a = k * 36
    r = _m.radians(a)
    mot += Pos(2.2 * _m.cos(r), 2.2 * _m.sin(r), 5) * Rot(0, 0, a) * Box(1.7, 0.55, 4)

# ---------------- экспорт ----------------
parts = [(f"neckL{i+1}_v9", layers[i]) for i in range(4)]
parts += [("neckL5_v9", L5), ("cart_body_v9", car), ("deck_v9", deck),
          ("rail_v9", rail), ("stop_v9", stop),
          ("roller_corner_v9", corner), ("_mock_nema14_v9", mot)]
parts += [(f"fin_f{i+1}_v9", fins[i]) for i in range(4)]
parts += [("drum_ring_v9", drum_ring), ("drum_top_v9", drum_top),
          ("lever_v9", lever), ("bigdrum_v9", bigdrum), ("bigdrum27_v9", bigdrum27), ("ratchet_hub_v9", rt_hub), ("ratchet_ring_v9", rt_ring)]
parts += [(f"riser_m{i+2}_v9", motor_risers[i]) for i in range(3)]
parts += [(f"guide_m{i+1}_v9", guides[i]) for i in range(4)]
parts += [(f"bush_m{i+1}_v9", bushes[i]) for i in range(4)]
for name, part in parts:
    p = part if isinstance(part, Part) else Part() + part
    export_stl(p, rf"{OUT}\{name}.stl")
    print(f"{name}: volume={p.volume:.0f} mm3, solids={len(p.solids())}")
print("export done")
