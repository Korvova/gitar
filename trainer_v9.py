def sector_face(a0, a1, r0, r1, n=24):
    aa = [a0 + (a1 - a0) * i / n for i in range(n + 1)]
    pts = [(r1 * _mm.cos(_mm.radians(a)), r1 * _mm.sin(_mm.radians(a))) for a in aa]
    pts += [(r0 * _mm.cos(_mm.radians(a)), r0 * _mm.sin(_mm.radians(a))) for a in reversed(aa)]
    return make_face(Polyline(*pts, close=True))

def slide_pocket(part, ang, z0, z1):
    rot = Rot(0, 0, ang)
    part -= rot * Pos(11.5, 0, (z0 + z1) / 2) * Cylinder(1.35, z1 - z0 + 0.2)  # камера узла
    part -= rot * BB(11.5, 14.2, -0.42, 0.42, z0 - 0.1, z1 + 0.1)              # прорезь шнура
    return part

