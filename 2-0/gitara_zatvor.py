# -*- coding: utf-8 -*-
"""ГИТАРА: «ЗАТВОР» — перемещение по грифу рукой (эскиз v0, 14.09.2026).

Идея владельца: на задней стороне грифа под большим пальцем площадка-затвор, как
затвор пистолета. При смене позиции рука тянет затвор к порожку или к деке, он
уходит на ±6 мм и возвращается пружинами в центр. Лента показывает, куда уехала
позиция, тележки переставляются. Пальцы 2–5 при этом остаются в тележках.

Две печатные детали:
  * ПЛАСТИНА 52×160×5 под дно секции-1, крепится теми же винтами стяжки М3 (Y 80, 150),
    в середине окно 24×52 с пазами под язычки затвора, по торцам окна карманы под
    пружины Ø4 и ниши под FSR; сбоку окна карман под 49E (вариант «Холл»);
  * ЗАТВОР 22×40×5 с ложбинкой под подушечку пальца, язычки по бокам ходят в пазах,
    по торцам пятачки под FSR и гнёзда пружин, в боку карман под магнит Ø4×2,
    снизу три кармана под вибромоторы 10×3 (волна «сдвинь руку туда»).
Датчики — оба сразу, чтобы сравнить: FSR402/RFP-602 на торцах (сила нажатия по
направлению) и магнит + 49E сбоку (положение). Пружины — Ø4 от авторучки, 2 шт.

Координаты секции-1: X поперёк, Y вдоль от порожка, Z вверх; дно секции Z=0,
пластина Z −5..0, затвор ходит в окне заподлицо с пластиной.
Запуск: .venv-b123d\\Scripts\\python gitara_zatvor.py -> Print/Print/zatvor_*_v0.stl
"""
import os
from build123d import *

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "Print", "Print")

L, W = 160.0, 52.0
PT = 5.0                          # толщина пластины
TIE = [(23.5, 80), (-23.5, 80), (23.5, 150), (-23.5, 150)]
# окно и затвор
TRAVEL = 6.0                      # ход ±6
SL_W, SL_L, SL_T = 22.0, 40.0, 5.0
WIN_W, WIN_L = SL_W + 0.6, SL_L + 2 * TRAVEL          # 22.6 × 52
WIN_YC = 46.0                                          # центр окна: большой палец под ладами 1–4
CLR = 0.3
TONGUE_W, TONGUE_T = 2.0, 2.0     # язычки затвора по бокам (X), высота по Z; пазы в стенках окна
TONGUE_Z0 = -3.5                  # низ язычка (паз Z −3.5..−1.5)
# пружины Ø4 от ручки, длина в сжатом состоянии ~6
SPR_R, SPR_DEPTH_WALL, SPR_DEPTH_SL = 2.2, 4.0, 4.0
SPR_X = (-7.5, 7.5)
# FSR на торцах окна: ниша под диск Ø13, пятачок Ø6 на торце затвора
FSR_R, FSR_NICHE = 6.6, 0.5
PUCK_R, PUCK_H = 2.4, 0.8
# Холл: магнит в правом боку затвора, датчик в пластине рядом (со сдвигом вдоль хода)
MAG_R, MAG_H = 2.1, 2.0
HALL_DY = TRAVEL + 0.5            # датчик впереди среднего положения магнита
SENS_W, SENS_L, SENS_T = 3.0, 4.0, 1.5
# моторы под пальцем
MOT_R, MOT_H = 5.2, 3.0
MOT_DY = (-13.0, 0.0, 13.0)


def BB(x0, x1, y0, y1, z0, z1):
    return Pos((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2) * Box(
        abs(x1 - x0), abs(y1 - y0), abs(z1 - z0))


# ---------------- пластина ----------------
plate = BB(-W / 2, W / 2, 0, L, -PT, 0)
for x, y in TIE:                                        # винты стяжки: самонарез Ø2.6
    plate -= Pos(x, y, -PT / 2) * Cylinder(1.3, PT + 0.2)
wy0, wy1 = WIN_YC - WIN_L / 2, WIN_YC + WIN_L / 2       # 20..72
plate -= BB(-WIN_W / 2, WIN_W / 2, wy0, wy1, -PT - 0.1, 0.1)                       # окно насквозь
for s in (-1, 1):                                       # пазы под язычки в боковых стенках окна
    plate -= BB(s * WIN_W / 2 - 0.1 * s, s * (WIN_W / 2 + TONGUE_W + CLR), wy0, wy1, TONGUE_Z0 - CLR, TONGUE_Z0 + TONGUE_T + CLR)
for yw, d in ((wy0, +1), (wy1, -1)):                    # торцы окна: гнёзда пружин и ниша FSR
    for sx in SPR_X:
        plate -= Pos(sx, yw - d * SPR_DEPTH_WALL / 2 + d * 0.05, -PT / 2) * Rot(90, 0, 0) * Cylinder(SPR_R, SPR_DEPTH_WALL + 0.1)
    plate -= Pos(0, yw - d * FSR_NICHE / 2 + d * 0.05, -PT / 2) * Rot(90, 0, 0) * Cylinder(FSR_R, FSR_NICHE + 0.1)
    # хвост FSR: щель от ниши вниз наружу пластины
    plate -= BB(-1.5, 1.5, yw - d * FSR_NICHE - (0.6 if d > 0 else 0), yw + (0.6 if d < 0 else 0), -PT - 0.1, -PT + 1.2)
# Холл: карман под 49E плашмя в пластине справа от окна, датчик лицом к окну
HALL_X0 = WIN_W / 2 + TONGUE_W + CLR + 0.8              # за пазом язычка
hy = WIN_YC + HALL_DY
plate -= BB(HALL_X0, HALL_X0 + SENS_T + 0.2, hy - SENS_L / 2 - 0.1, hy + SENS_L / 2 + 0.1, -PT + 0.4, -PT + 0.4 + SENS_W + 0.2)  # датчик стоит на ребре, лицом к окну
plate -= BB(HALL_X0, HALL_X0 + SENS_T + 0.2, hy - 1.5, hy + 1.5, -PT - 0.1, -PT + 0.5)        # ножки вниз
plate -= BB(HALL_X0, W / 2 + 0.1, hy - 1.2, hy + 1.2, -PT - 0.1, -PT + 1.0)                    # канавка проводов к краю
# канавки проводов моторов: от окна к краю (петля идёт по низу пластины)
plate -= BB(-1.0, 1.0, wy1, L, -PT - 0.1, -PT + 1.0)

# ---------------- затвор ----------------
sy0, sy1 = -SL_L / 2, SL_L / 2                          # локальные Y, центр = 0
sl = BB(-SL_W / 2, SL_W / 2, sy0, sy1, -SL_T, 0)
for s in (-1, 1):                                       # язычки с фаской снизу (печать плашмя верхом на стол)
    sl += BB(s * SL_W / 2, s * (SL_W / 2 + TONGUE_W), sy0 + 6, sy1 - 6, TONGUE_Z0, TONGUE_Z0 + TONGUE_T)
sl -= Pos(0, 0, -SL_T - 39.2) * Sphere(40.0)            # ложбинка 0.8 мм под подушечку пальца
for yw, d in ((sy0, -1), (sy1, +1)):                    # торцы: гнёзда пружин и пятачки под FSR
    for sx in SPR_X:
        sl -= Pos(sx, yw - d * SPR_DEPTH_SL / 2 + d * 0.05, -SL_T / 2) * Rot(90, 0, 0) * Cylinder(SPR_R, SPR_DEPTH_SL + 0.1)
    sl += Pos(0, yw + d * PUCK_H / 2, -SL_T / 2) * Rot(90, 0, 0) * Cylinder(PUCK_R, PUCK_H)
sl -= Pos(SL_W / 2 - MAG_H / 2 + 0.05, 0, -SL_T / 2) * Rot(0, 90, 0) * Cylinder(MAG_R, MAG_H + 0.1)    # магнит в правом боку, ось по X
for dy in MOT_DY:                                       # моторы снизу, заподлицо
    sl -= Pos(0, dy, -SL_T + 1.2) * Cylinder(MOT_R, MOT_H + 0.2)
    sl -= BB(-0.8, 0.8, dy, sy1 + 0.1, -SL_T - 0.1, -SL_T + 0.8)

for name, part in (("zatvor_plate_v0", plate), ("zatvor_slide_v0", sl)):
    p = Part() + part
    export_stl(p, os.path.join(OUT, name + ".stl"))
    bb = p.bounding_box()
    print(f"{name}: volume={p.volume:.0f} mm3, solids={len(p.solids())}, габарит {bb.size.X:.1f}×{bb.size.Y:.1f}×{bb.size.Z:.1f}")
print(f"окно Y {wy0}..{wy1}, ход ±{TRAVEL}, датчик Холла Y={hy}, магнит на затворе X=+{SL_W/2:.0f}")
print("export done")
