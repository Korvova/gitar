# -*- coding: utf-8 -*-
"""ТЕСТ-НАБОР механизма «палка» v2 — БЕЗ ШТИФТОВ (идея юзера):
во всех шарнирах печатный ШТЫРЁК Ø5 в одной детали и ЯМКА Ø6 в другой.
Запуск: .venv-b123d\\Scripts\\python palka_test.py
Сборка: всё просто надевается сверху. Кривошипов три (r6 / 6.5 / 7) —
регулировка хода выбором детали.
"""
from build123d import *
import math as _m

OUT = r"C:\App\gitar\2-0\Print\Print"
STUD = 2.5                                     # штырёк Ø5 (не мельчим!)
HOLE = 3.0                                     # ямка Ø6 — зазор 1 мм, крутится свободно


def BB(x0, x1, y0, y1, z0, z1):
    return Pos((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2) * Box(
        abs(x1 - x0), abs(y1 - y0), abs(z1 - z0))


def spline_cut(h, t=0.0):
    cut = Pos(0, 0, h / 2) * Cylinder(2.45 + t, h + 0.2)
    for k in range(10):
        a = k * 36
        r = _m.radians(a)
        cut += Pos((2.4 + t) * _m.cos(r), (2.4 + t) * _m.sin(r), h / 2) * \
               Rot(0, 0, a) * Box(1.3, 0.95 + 2 * t, h + 0.2)
    return cut


# ---------------- плита-стенд (канал удлинён на север под ход r8.5) -------
plate = BB(0, 255, -35, 45, 0, 3)
plate += BB(16, 20, -35, 43, 3, 11)            # рельса канала ВЫСОКАЯ (физика:
plate += BB(40, 44, 26, 43, 3, 11)             # низкие вели только юбки, палубу
plate += BB(40, 44, -35, -26, 3, 11)           # плыло) — теперь ведут всю тележку
plate += BB(40, 44, -26, 26, 7.4, 11)          # НАВЕСНАЯ стенка над проёмом:
                                               # плечо машет ПОД ней (верх 6.6)
plate += BB(16, 44, -35, -33, 3, 11)           # ТОРЦЫ канала (юг и север):
plate += BB(16, 44, 43, 45, 3, 11)             # тележка не вылетает из концов
plate += BB(20, 44, -35, 43, 3, 5.0)           # НАСТИЛ канала (подложка юзера):
plate += BB(44, 90, -8.5, 4.5, 3, 5.0)         # плечо и тележка ЛЕЖАТ, не висят
plate += Pos(95, 0, 4) * Cylinder(5.5, 2)      # стойка оси (ось смещена на +2:
plate += Pos(95, 0, 5.95) * Cylinder(STUD, 1.9)   # нейтраль тележки = центр канала)
plate -= Pos(95, 0, 4.4) * Cylinder(0.95, 5.2)    # дырка Ø1.9 под винт M2 шайбы
# губок, столика и шатуна больше нет: спица-шатун сама висит на двух штырьках
plate += BB(80, 110, -28, -14, 3, 5.0)         # ПОДЛОЖКА узла угол-1 (идея юзера):
plate += BB(112, 208, -27, -9.7, 3, 6.4)       # плечо не перекосится; полка под
                                               # пролётом спицы (зазор 0.2, широкая:
                                               # хвост гуляет к северу на +11)
plate -= Pos(120, -32, 1.5) * Cylinder(3.0, 3.2)  # ямки мостиков-прижимов спицы;
plate -= Pos(120, -6, 1.5) * Cylinder(3.0, 3.2)   # мост-186 севернее: при r10
plate -= Pos(186, -29, 1.5) * Cylinder(3.0, 3.2)  # спица почти задевала его ногу
plate -= Pos(186, -3, 1.5) * Cylinder(3.0, 3.2)
plate -= Pos(65, -33, 1.5) * Cylinder(3.0, 3.2)   # ямки НИЗКОГО моста над длинным
plate -= Pos(65, 19, 1.5) * Cylinder(3.0, 3.2)    # плечом; north дальше: юзер поймал,
                                               # что нога ограничивала мах плеча
for by in (-14, 16):                           # ямки ДВУХ высоких мостов: в любой
    plate -= Pos(10.5, by, 1.5) * Cylinder(3.0, 3.2)   # фазе хода хотя бы один
    plate -= Pos(49.5, by, 1.5) * Cylinder(3.0, 3.2)   # накрывает тележку
# КОЛОДЕЦ МОТОРА NEMA14 (мотор снизу, вал вверх): Ø37.4 + уши M3 вдоль X
plate -= Pos(229, -15, 1.5) * Cylinder(18.7, 3.2)
for sgx in (-1, 1):
    plate -= Pos(229 + sgx * 21.925, -15, 1.5) * Cylinder(1.7, 3.2)
# отверстия ножек по углам (шип Ø4.75)
for lx, ly in ((10, -30), (10, 30), (245, -30), (245, 30)):
    plate -= Pos(lx, ly, 1.5) * Cylinder(2.45, 3.2)

# ---------------- треугольник: дырка оси + два бугорка вверх ----------------
tri = Pos(0, 0, 0.8) * Cylinder(11, 1.6)
tri += BB(-66.6, 0, -2.5, 2.5, 0, 1.6)         # плечо 65 к серьге
tri += BB(-2.5, 2.5, -22.8, 0, 0, 1.6)         # плечо 21.2 к спице
tri += Pos(-65, 0, 0.8) * Cylinder(5.5, 1.6)   # площадки под штырьки
tri += Pos(0, -21.2, 0.8) * Cylinder(5.5, 1.6)
tri -= Pos(0, 0, 0.8) * Cylinder(HOLE, 1.8)    # дырка оси (на бугорок стойки)
tri += Pos(0, -21.2, 3.8) * Cylinder(STUD, 4.4)  # бугорок угла-1 ДЛИННЫЙ (физика:
                                                 # спица пыталась соскочить вверх)
tri += Pos(-65, 0, 4.3) * Cylinder(STUD, 5.4)    # штырь tip в вилку палубы; верх 12:
                                                 # НЕ достаёт до высоких мостов (13.3)

# ---------------- спица-шатун (идея юзера): длинная, ДВЕ дырки, без губок ----
# ц-ц 134.25 = расстояние угол-1 (95,-23.2) → ось кривошипа (229,-15)
spica = BB(0, 114, -2.5, 2.5, 0, 1.6)
spica += Pos(4, 0, 0.8) * Cylinder(5.5, 1.6)
spica -= Pos(4, 0, 0.8) * Cylinder(HOLE, 1.8)          # на штырёк угла-1
spica += BB(110, 141.5, -2.5, 2.5, 1.4, 3.0)           # хвост ПРИПОДНЯТ над диском кривошипа:
spica += Pos(138.25, 0, 2.2) * Cylinder(5.5, 1.6)      # ступенька ДО диска даже при r8.5
spica -= Pos(138.25, 0, 2.2) * Cylinder(HOLE, 1.8)     # прямо на палец кривошипа

# серьги больше НЕТ (идея юзера): штырь плеча ходит прямо в щели палубы тележки

# -------- кривошипы (5 шт: r6..r8.5) — радиус пальца задаёт ход тележки:
# ход ≈ 6.15*r - 10.6 (мёртвый ход люфтов Ø5/Ø6); r8/8.5 добивают до 40
cranks = []
for rr, disk in ((6.0, 11), (6.5, 11), (7.0, 11), (8.0, 11),
                 (8.5, 11), (9.0, 11.5), (10.0, 12.5)):
    c = Pos(0, 0, 1.25) * Cylinder(disk, 2.5)  # диск растёт с радиусом пальца
    c -= spline_cut(2.5, 0)                    # звёздочка на шестерню мотора
    c += Pos(rr, 0, 5.0) * Cylinder(STUD, 5.0)  # палец-бугорок (высокий)
    cranks.append((rr, c))

# ---------------- тележка: паз снизу для серьги + выпуклость вниз ---------
# юг длиннее: под тележку заходит КОНЕЦ ПЛЕЧА (пад Ø11), паз до -16.
# Привод — КУЛИСА (идея юзера): щель в палубе, в ней ходит штырь плеча:
# вдоль канала люфт 1 мм (привод), поперёк ±4.25 (дуга конца плеча)
cart = BB(-9.65, 9.65, -18, 12, 0, 8)          # шире: зазор в канале 0.35/сторону
cart -= BB(-9.6, 9.6, -16, 9.5, -0.1, 4.5)     # паз ГЛУБОКИЙ под плечо и пад
cart -= BB(-9.7, 7.5, -11, -5, 4.4, 8.1)       # ВИЛКА-кулиса: открыта на запад,
                                               # торец глубже (штырь не упирался бы)
                                               # (дуга штыря при r8.5 шире; сборка
                                               # надвиганием сбоку)

# ---------------- мостик-прижим спицы (2 шт): физика показала, что спицу
# выдавливает ВВЕРХ по пальцу — мостик держит её сверху (зазор 0.2).
# Печать перекладиной вниз; при установке переворачивается штырьками в ямки.
bridge = BB(-4, 4, -14.5, 14.5, 0, 1.6)        # перекладина (низ над спицей 8.4)
bridge += BB(-4, 4, -14.5, -11.5, 1.6, 7.0)    # ножки (мимо полки)
bridge += BB(-4, 4, 11.5, 14.5, 1.6, 7.0)
bridge += Pos(0, -13, 8.4) * Cylinder(STUD, 2.8)   # штыри в ямки плиты
bridge += Pos(0, 13, 8.4) * Cylinder(STUD, 2.8)

# ВЫСОКИЙ мост над тележкой (низ перекладины 13.3, тележка ездит под ним)
bridge_high = BB(-4, 4, -21, 21, 0, 1.6)
bridge_high += BB(-4, 4, -21, -18, 1.6, 11.9)  # ножки: 13.3-3.0 = 10.3 высоты
bridge_high += BB(-4, 4, 18, 21, 1.6, 11.9)
bridge_high += Pos(0, -19.5, 13.3) * Cylinder(STUD, 2.8)
bridge_high += Pos(0, 19.5, 13.3) * Cylinder(STUD, 2.8)

# НИЗКИЙ мост над длинным плечом (низ перекладины 6.8, плечо машет под ним);
# ДЛИННЫЙ: ноги за пределами маха плеча ±16.6 при r10 (нашёл юзер)
bridge_low = BB(-4, 4, -27.5, 27.5, 0, 1.6)
bridge_low += BB(-4, 4, -27.5, -24.5, 1.6, 5.4)   # ножки: 6.8-3.0 = 3.8 высоты
bridge_low += BB(-4, 4, 24.5, 27.5, 1.6, 5.4)
bridge_low += Pos(0, -26, 6.8) * Cylinder(STUD, 2.8)
bridge_low += Pos(0, 26, 6.8) * Cylinder(STUD, 2.8)

# ---------------- шайба оси треугольника: запирает диск сверху (винт M2) ----
washer = Pos(0, 0, 0.75) * Cylinder(5.0, 1.5)
washer -= Pos(0, 0, 0.75) * Cylinder(1.2, 1.7)     # под M2 свободно

# ---------------- ножки ----------------
leg = Pos(0, 0, 13) * Cylinder(5, 26)
leg += Pos(0, 0, 27.5) * Cylinder(2.35, 3.0)
# ---------------- фальш-мотор: заглушка с пеньком под звёздочку -----------
plug = Pos(0, 0, 1) * Cylinder(20.5, 2)
plug += Pos(0, 0, -1.5) * Cylinder(18.5, 3.1)
plug += Pos(0, 0, 3.25) * Cylinder(2.45, 2.5)  # пенёк Ø4.9 короткий: держит кривошип, под спицей не торчит

parts = [("ptest_plate_v2", plate), ("ptest_triangle_v2", tri),
         ("ptest_leg_v1", leg), ("ptest_plug_v2", plug),
         ("ptest_spica_v2", spica), ("ptest_bridge_v1", bridge),
         ("ptest_bridge_low_v1", bridge_low), ("ptest_bridge_high_v1", bridge_high),
         ("ptest_washer_v1", washer), ("ptest_cart_v2", cart)]
parts += [(f"ptest_crank_r{str(rr).replace('.', '')}_v2", c) for rr, c in cranks]
for name, part in parts:
    p = part if isinstance(part, Part) else Part() + part
    export_stl(p, rf"{OUT}\{name}.stl")
    print(f"{name}: volume={p.volume:.0f} mm3, solids={len(p.solids())}")
print("export done")
