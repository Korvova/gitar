# -*- coding: utf-8 -*-
"""
Тест-купон «поворотного ключа» (идея юзера): плашка с крестовой прорезью +
ключ-лопатка с каналом нити. Открыто (вдоль A) — нить свободно протягивается;
поднял до щелчка -> повернул 90° (нить S-ом вокруг шейки) -> опустил в B —
заперто, бугры защёлкнулись под плашкой. Проверить: держит ли рабочую тягу,
удобен ли поворот, не режет ли нить. Потом врезаем пару таких в диск Ø27.
Запуск: .venv-b123d\\Scripts\\python keylock.py
"""
from build123d import *

OUT = r"C:\App\gitar\2-0\Print\Print"

def BB(x0, x1, y0, y1, z0, z1):
    return Pos((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2) * Box(
        abs(x1 - x0), abs(y1 - y0), abs(z1 - z0))

# ---------- плашка ----------
plate = BB(0, 22, 0, 14, 0, 4.4)
plate -= BB(11 - 4.7, 11 + 4.7, 7 - 1.15, 7 + 1.15, -0.1, 4.5)     # прорезь A (вдоль X)
plate -= BB(11 - 1.15, 11 + 1.15, 7 - 4.7, 7 + 4.7, -0.1, 4.5)     # прорезь B
plate -= Pos(11, 7, 2.2) * Rot(0, 90, 0) * Cylinder(1.05, 24)      # канал нити Ø2.1
# ножки-подставки, чтобы буграм ключа было куда выйти снизу
for cx in (2.5, 19.5):
    plate += BB(cx - 2.5, cx + 2.5, 0, 14, -3, 0)

# ---------- ключ ----------
# лопасть 2.1x8, проходит плашку насквозь; внизу бугры-защёлки
key = BB(-4, 4, -1.05, 1.05, -1.6, 4.4)                            # лопасть
key += Pos(0, 0, 5.9) * Cylinder(1.8, 3.0)                         # шейка Ø3.6
key += BB(-4.5, 4.5, -1.05, 1.05, 7.4, 10.4)                       # ручка-флажок
key -= Pos(0, 0, 2.2) * Rot(0, 90, 0) * Cylinder(0.95, 9)          # канал нити Ø1.9
for sx in (-1, 1):                                                 # бугры-защёлки:
    for sy in (-1, 1):                                             # по БОКАМ лопасти
        key += Pos(sx * 3.0, sy * 1.05, -1.15) * Rot(0, 90, 0) * Cylinder(0.42, 1.6)

for name, part in (("keylock_plate_v1", plate), ("keylock_key_v1", key)):
    p = part if isinstance(part, Part) else Part() + part
    export_stl(p, rf"{OUT}\{name}.stl")
    print(f"{name}: volume={p.volume:.0f} mm3, solids={len(p.solids())}")
print("done")
